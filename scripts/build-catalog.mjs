// Build-time generator for src/lib/catalog.ts.
// Source: HYG Database v4.1 (astronexus/HYG-Database) — CC BY-SA 4.0.
//   https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv
// Keep only stars a phone can plausibly see (Vmag <= 6.5) and emit a flat
// [raHours, decDeg, vmag, ...] array. Run: `node scripts/build-catalog.mjs`.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const URL =
  'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv';
const MAG_LIMIT = 6.5;
const OUT = join(import.meta.dirname, '..', 'src', 'lib', 'catalog.ts');

const parseCsvLine = (line) => {
  const out = [];
  let cur = '';
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i++;
        } else q = false;
      } else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') {
      out.push(cur);
      cur = '';
    } else cur += c;
  }
  out.push(cur);
  return out;
};

const res = await fetch(URL);
if (!res.ok) throw new Error(`fetch ${res.status}`);
const text = await res.text();
const lines = text.split('\n');
const head = parseCsvLine(lines[0]);
const iRa = head.indexOf('ra');
const iDec = head.indexOf('dec');
const iMag = head.indexOf('mag');
if (iRa < 0 || iDec < 0 || iMag < 0) throw new Error('columns not found');

const flat = [];
for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line) continue;
  const f = parseCsvLine(line);
  const ra = parseFloat(f[iRa]);
  const dec = parseFloat(f[iDec]);
  const mag = parseFloat(f[iMag]);
  if (!Number.isFinite(ra) || !Number.isFinite(dec) || !Number.isFinite(mag)) continue;
  if (mag > MAG_LIMIT || mag < -2) continue;
  flat.push(
    Math.round(ra * 1e5) / 1e5,
    Math.round(dec * 1e4) / 1e4,
    Math.round(mag * 1e2) / 1e2,
  );
}

const count = flat.length / 3;
const body = `// AUTO-GENERATED by scripts/build-catalog.mjs — do not edit by hand.
// Source: HYG Database v4.1 (astronexus/HYG-Database), License CC BY-SA 4.0.
// Filtered to Vmag <= ${MAG_LIMIT}. Triples: [raHours, decDeg, vmag, ...] (J2000).
export const CATALOG_MAG_LIMIT = ${MAG_LIMIT};
export const CATALOG_COUNT = ${count};
export const CATALOG: number[] = [${flat.join(',')}];
`;
writeFileSync(OUT, body);
console.log(`catalog.ts: ${count} stars, ${(body.length / 1024).toFixed(0)} KB`);
