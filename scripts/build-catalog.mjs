// Build-time generator for src/lib/catalog.ts.
// Source: HYG Database v4.1 (astronexus/HYG-Database) — CC BY-SA 4.0.
//   https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv
// Keep only stars a phone can plausibly see (Vmag <= 6.5) and emit a flat
// [raHours, decDeg, vmag, ...] array plus a parallel NAMES[] with the display label
// (proper name → Greek letter + constellation → Flamsteed + constellation → '').
// Run: `node scripts/build-catalog.mjs`.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const URL =
  'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv';
const MAG_LIMIT = 6.5;
const OUT = join(import.meta.dirname, '..', 'src', 'lib', 'catalog.ts');

const parseCsvLine = (line) => {
  const out = [];
  let cur = '';
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i++;
        } else q = false;
      } else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') {
      out.push(cur);
      cur = '';
    } else cur += c;
  }
  out.push(cur);
  return out;
};

const res = await fetch(URL);
if (!res.ok) throw new Error(`fetch ${res.status}`);
const text = await res.text();
const lines = text.split('\n');
const head = parseCsvLine(lines[0]);
const iRa = head.indexOf('ra');
const iDec = head.indexOf('dec');
const iMag = head.indexOf('mag');
const iProper = head.indexOf('proper');
const iBayer = head.indexOf('bayer');
const iFlam = head.indexOf('flam');
const iCon = head.indexOf('con');
if (iRa < 0 || iDec < 0 || iMag < 0) throw new Error('columns not found');

/** HYG writes Bayer as three letters (`Alp`); the app shows the Greek glyph. */
const GREEK = {
  Alp: 'α', Bet: 'β', Gam: 'γ', Del: 'δ', Eps: 'ε', Zet: 'ζ', Eta: 'η', The: 'θ',
  Iot: 'ι', Kap: 'κ', Lam: 'λ', Mu: 'μ', Nu: 'ν', Xi: 'ξ', Omi: 'ο', Pi: 'π',
  Rho: 'ρ', Sig: 'σ', Tau: 'τ', Ups: 'υ', Phi: 'φ', Chi: 'χ', Psi: 'ψ', Ome: 'ω',
};

/** Display label of a row: proper name, else `α UMi`, else `51 Peg`, else ''. */
const labelFor = (f) => {
  const proper = (f[iProper] ?? '').trim();
  if (proper) return proper;
  const con = (f[iCon] ?? '').trim();
  const bayer = (f[iBayer] ?? '').trim();
  if (bayer && con) return `${GREEK[bayer] ?? bayer} ${con}`;
  const flam = (f[iFlam] ?? '').trim();
  if (flam && con) return `${flam} ${con}`;
  return '';
};

const flat = [];
const names = [];
for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line) continue;
  const f = parseCsvLine(line);
  const ra = parseFloat(f[iRa]);
  const dec = parseFloat(f[iDec]);
  const mag = parseFloat(f[iMag]);
  if (!Number.isFinite(ra) || !Number.isFinite(dec) || !Number.isFinite(mag)) continue;
  if (mag > MAG_LIMIT || mag < -2) continue;
  flat.push(
    Math.round(ra * 1e5) / 1e5,
    Math.round(dec * 1e4) / 1e4,
    Math.round(mag * 1e2) / 1e2,
  );
  names.push(labelFor(f));
}

const count = flat.length / 3;
const named = names.filter(Boolean).length;
const body = `// AUTO-GENERATED by scripts/build-catalog.mjs — do not edit by hand.
// Source: HYG Database v4.1 (astronexus/HYG-Database), License CC BY-SA 4.0.
// Filtered to Vmag <= ${MAG_LIMIT}. Triples: [raHours, decDeg, vmag, ...] (J2000).
// NAMES is parallel to the triples (NAMES[i] belongs to star i); '' = no label.
export const CATALOG_MAG_LIMIT = ${MAG_LIMIT};
export const CATALOG_COUNT = ${count};
export const CATALOG: number[] = [${flat.join(',')}];
export const NAMES: string[] = [${names.map((n) => JSON.stringify(n)).join(',')}];
`;
writeFileSync(OUT, body);
console.log(
  `catalog.ts: ${count} stars (${named} named), ${(body.length / 1024).toFixed(0)} KB`,
);
